# Simple Tuple Demonstration

# Create a tuple of fruits
fruits = ("apple", "banana", "cherry")

# Print the tuple
print("Tuple of fruits:", fruits)

# Accessing elements in the tuple
print("First fruit:", fruits[0])
print("Last fruit:", fruits[-1])

# Loop through the tuple and print each fruit
print("All fruits in the tuple:")
for fruit in fruits:
    print(fruit)
